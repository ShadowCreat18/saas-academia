        <h1>Aviso de Privacidad</h1>
        
        <p><strong>Última actualización:</strong> 16 de Septiembre de 2026</p>

        <p>De conformidad con lo establecido en la Ley Federal de Protección de Datos Personales en Posesión de los Particulares (en adelante la "Ley"), <strong>Christian Israel Esparza Solis</strong> (en adelante "El Responsable"), con domicilio en el Estado de Zacatecas, México, pone a su disposición el presente Aviso de Privacidad.</p>

        <h2>1. Identidad y Domicilio del Responsable</h2>
        <p><strong>Christian Israel Esparza Solis</strong>, operando bajo el nombre comercial <strong>Dark Amethyst Studio / AcademiaCloud</strong>, es el responsable del uso y protección de sus datos personales. Para cualquier duda relacionada con la protección de sus datos personales podrá contactarnos en el correo electrónico oficial de contacto de la plataforma.</p>

        <h2>2. Rol como Procesador de Datos (B2B2C)</h2>
        <p>AcademiaCloud es una plataforma de software como servicio (SaaS) que permite a academias deportivas (los "Clientes") gestionar la información de sus jugadores, entrenadores y tutores (los "Usuarios Finales"). En este contexto:</p>
        <ul>
            <li><strong>Las Academias (Nuestros Clientes):</strong> Actúan como los <em>Controladores de los Datos</em>. Ellos son responsables de recabar el consentimiento explícito de los padres, tutores o jugadores para registrar su información en la plataforma.</li>
            <li><strong>AcademiaCloud:</strong> Actúa únicamente como <em>Procesador de los Datos</em>. Proporcionamos la infraestructura tecnológica para almacenar y procesar la información por cuenta de la Academia. No utilizamos los datos de los Usuarios Finales para fines propios de marketing ni los vendemos a terceros.</li>
        </ul>

        <h2>3. Datos Personales que se recaban</h2>
        <p>Para llevar a cabo las finalidades descritas en el presente aviso, recabamos las siguientes categorías de datos:</p>
        <ul>
            <li><strong>De nuestros Clientes (Dueños de Academias):</strong> Nombre, correo electrónico, datos de facturación e información fiscal.</li>
            <li><strong>De los Usuarios Finales (Ingresados por las Academias):</strong> Nombre, fecha de nacimiento, fotografías (opcional), historial deportivo, nombre del tutor, correo del tutor y número de teléfono.</li>
            <li><strong>Datos Sensibles:</strong> La plataforma puede almacenar datos sobre el estado físico o de salud (tallas, alergias o condiciones médicas relevantes para la práctica deportiva) únicamente si la Academia así lo requiere y habiendo obtenido el consentimiento del padre o tutor.</li>
        </ul>

        <h2>4. Finalidades del Tratamiento de Datos</h2>
        <p>Los datos personales que recabamos serán utilizados para las siguientes finalidades necesarias:</p>
        <ul>
            <li>Proveer el servicio de gestión de academias (plataforma web).</li>
            <li>Permitir el acceso a los portales de administradores y tutores.</li>
            <li>Procesamiento de pagos de suscripción a través de nuestra pasarela de pagos segura (Stripe).</li>
            <li>Generación de recibos y facturas.</li>
            <li>Brindar soporte técnico y atención al cliente.</li>
        </ul>

        <h2>5. Transferencia de Datos y Procesamiento de Pagos</h2>
        <p>Para el procesamiento de pagos de suscripción, utilizamos los servicios de <strong>Stripe</strong>. AcademiaCloud no almacena directamente números de tarjetas de crédito o débito; dicha información es procesada de manera cifrada y directa por Stripe, sujeto a su propio Aviso de Privacidad.</p>
        <p>No realizamos transferencias de datos personales a terceros para fines comerciales o de mercadotecnia.</p>

        <h2>6. Derechos ARCO</h2>
        <p>Usted tiene derecho a conocer qué datos personales tenemos, para qué los utilizamos y las condiciones del uso que les damos (Acceso). Asimismo, es su derecho solicitar la corrección de su información personal en caso de que esté desactualizada, sea inexacta o incompleta (Rectificación); que la eliminemos de nuestros registros o bases de datos (Cancelación); así como oponerse al uso de sus datos personales para fines específicos (Oposición). Estos derechos se conocen como derechos ARCO.</p>
        <p><strong>Nota importante para Usuarios Finales (Jugadores/Tutores):</strong> Si usted desea ejercer sus derechos ARCO respecto a la información ingresada por una academia deportiva, deberá dirigir su solicitud directamente a la administración de dicha academia (el Controlador de Datos). AcademiaCloud colaborará con la academia para ejecutar la instrucción en nuestros sistemas.</p>

        <h2>7. Cambios al Aviso de Privacidad</h2>
        <p>El presente aviso de privacidad puede sufrir modificaciones, cambios o actualizaciones derivadas de nuevos requerimientos legales; de nuestras propias necesidades por los productos o servicios que ofrecemos; de nuestras prácticas de privacidad, o por otras causas. Nos comprometemos a mantenerlo informado sobre los cambios que pueda sufrir el presente aviso de privacidad a través de la plataforma web.</p>

